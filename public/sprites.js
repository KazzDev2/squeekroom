// ---------- rasterize + cache ----------
const RGB = PALETTE.map((hex) => (hex ? [parseInt(hex.slice(1, 3), 16), parseInt(hex.slice(3, 5), 16), parseInt(hex.slice(5, 7), 16)] : null));
const cache = new WeakMap(); // sprite -> Map(key -> canvas)
const remapKeys = new WeakMap();
function remapKey(m) {
  if (!m) return "";
  let k = remapKeys.get(m);
  if (!k) { k = Array.from(m, (v) => (v | 0).toString(16)).join(""); remapKeys.set(m, k); }
  return k;
}
function frameCanvas(s, fi, flip, map) {
  let per = cache.get(s);
  if (!per) { per = new Map(); cache.set(s, per); }
  const key = `${fi}|${flip ? 1 : 0}|${remapKey(map)}`;
  let c = per.get(key);
  if (c) return c;
  c = document.createElement("canvas");
  c.width = s.w; c.height = s.h;
  const g = c.getContext("2d"), img = g.createImageData(s.w, s.h), d = img.data, px = s.frames[fi];
  for (let y = 0; y < s.h; y++) for (let x = 0; x < s.w; x++) {
    let v = px[y * s.w + (flip ? s.w - 1 - x : x)];
    if (!v) continue;
    if (map) v = map[v] | 0;
    const rgb = RGB[v];
    if (!rgb) continue;
    const o = (y * s.w + x) * 4;
    d[o] = rgb[0]; d[o + 1] = rgb[1]; d[o + 2] = rgb[2]; d[o + 3] = 255;
  }
  g.putImageData(img, 0, 0);
  per.set(key, c);
  return c;
}
function frameIndex(s, frame, o) {
  const n = s.frames.length;
  if (n <= 1) return 0;
  let f;
  if (s.angleFrames && typeof o.angle === "number") f = Math.floor(o.angle * 24);
  else if (s.seq) f = s.seq[(((frame | 0) % s.seq.length) + s.seq.length) % s.seq.length];
  else f = frame | 0;
  return ((f % n) + n) % n;
}

// drawSprite(ctx, sprite, frame, x, y, { flip, remap, skin, angle, tier, w, h, t })
//   sprite: a SPRITES entry (or its id). (x, y) is the top-left of the box the caller reserves; with
//   w/h given and no ox/oy, art smaller than the box is centred horizontally and stands on its bottom.
function drawSprite(ctx, sprite, frame, x, y, opts) {
  const o = opts || {};
  const s = typeof sprite === "string" ? SPRITES[sprite] : sprite;
  if (!s) return false;
  if (typeof s === "function") { s(ctx, frame, x, y, o); return true; }
  const map = o.remap || (o.skin && SKIN_REMAPS[o.skin]) || null;
  const flip = !!o.flip;
  const c = frameCanvas(s, frameIndex(s, frame, o), flip, map);
  let dx = x, dy = y;
  if (s.ox != null) dx += flip && o.w ? o.w - s.w - s.ox : s.ox;
  else if (o.w) dx += Math.floor((o.w - s.w) / 2);
  if (s.oy != null) dy += s.oy;
  else if (o.h) dy += o.h - s.h;
  ctx.drawImage(c, Math.round(dx), Math.round(dy));
  return true;
}

